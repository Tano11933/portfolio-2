const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')

;(async () => {
  const vite = await import('vite')
  const production = process.env.GALLERY_PRODUCTION === '1'
  const server = production
    ? await vite.preview({ preview: { host: '127.0.0.1', port: 5183, strictPort: true } })
    : await vite.createServer({ server: { host: '127.0.0.1', port: 5183, strictPort: true } })
  if (!production) await server.listen()
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
  const errors = []
  const results = []
  await fs.mkdir('anti-slop/verification', { recursive: true })
  try {
    for (const width of [1440, 768, 390, 360]) {
      console.log(`Checking ${width}`)
      const page = await browser.newPage({ viewport: { width, height: 900 }, reducedMotion: 'reduce' })
      page.on('pageerror', (error) => errors.push(error.message))
      const fullRequests=[]
      page.on('request', request=>{if(request.resourceType()==='image' && /-full[-.]/.test(request.url())) fullRequests.push(request.url())})
      await page.goto('http://127.0.0.1:5183/')
      await page.locator('#eaglejeans .project-gallery').scrollIntoViewIfNeeded()
      const gallery = page.getByRole('group', { name: 'EagleJeans screenshots', exact: true })
      await gallery.waitFor()
      await gallery.scrollIntoViewIfNeeded()
      await gallery.locator('img').first().waitFor({state:'visible'})
      await page.waitForFunction(() => [...document.querySelectorAll('#eaglejeans .ag img')].filter(i=>i.getBoundingClientRect().width>0).every(i=>i.complete && i.naturalWidth>0))
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Page overflow at ${width}`)
      assert.equal(await gallery.locator('.ag__selectors button').count(), 5)
      if (width===1440) {
        await gallery.locator('.ag__panel').nth(1).hover()
        assert.equal(await gallery.getByRole('button',{name:'2. Order detail',exact:true}).getAttribute('aria-pressed'),'true')
        results.push({hoverExpansion:'pass'})
      }
      await gallery.getByRole('button', { name: '2. Order detail', exact: true }).click()
      await gallery.getByRole('button', { name: '2. Order detail', exact: true }).press('ArrowRight')
      assert.equal(await gallery.getByRole('button', { name: '3. Production report', exact: true }).getAttribute('aria-pressed'), 'true')
      const enlarge = gallery.getByRole('button', { name: 'Enlarge EagleJeans: Production report', exact: true })
      await enlarge.click()
      const dialog = page.getByRole('dialog')
      await dialog.waitFor({ state: 'visible' })
      await dialog.getByRole('button', { name: 'Next screenshot', exact: true }).click()
      assert.match(await dialog.innerText(), /4 \/ 5/)
      if (width===1440) {
        await page.waitForFunction(()=>document.querySelector('dialog img')?.naturalWidth>0)
        const screenBox=await dialog.locator('.ag-device__screen').boundingBox()
        const islandBox=await dialog.locator('.ag-device__island').boundingBox()
        assert.ok(screenBox.y >= islandBox.y+islandBox.height, 'Dynamic Island overlaps app header')
        await page.screenshot({path:'anti-slop/verification/eagle-iphone-dialog.png'})
      }
      await dialog.getByRole('button', { name: 'Full size', exact: true }).click()
      assert.equal(await dialog.getByRole('button', { name: 'Fit image' }).getAttribute('aria-pressed'), 'true')
      await page.keyboard.press('Escape')
      await dialog.waitFor({ state: 'hidden' })
      assert.equal(await gallery.getByRole('button', { name: /Enlarge EagleJeans:/ }).evaluate(el=>el===document.activeElement), true)
      await gallery.getByRole('button', { name: '1. Owner dashboard', exact: true }).click()
      await page.evaluate(() => window.scrollTo(0, document.querySelector('#eaglejeans').getBoundingClientRect().top + scrollY - 80))
      await page.screenshot({ path: `anti-slop/verification/work-${width}.png` })
      const size = await page.locator('#eaglejeans .project-gallery').boundingBox()
      results.push({ width, galleryHeight: size.height, overflow: false, keyboardAndDialog: 'pass' })
      for (const slug of ['arthabooks','reusemart','bookhive','spotify-clone','t2kav-gym','padukuhan-tritis']) {
        await page.locator(`#${slug} .project-gallery`).scrollIntoViewIfNeeded()
        await page.locator(`#${slug} .ag`).waitFor()
        const count = await page.locator(`#${slug} .ag__selectors button`).count()
        assert.ok(count>=4 && count<=5, `${slug}: invalid count ${count}`)
      }
      if (width===390) {
        await page.locator('#t2kav-gym').scrollIntoViewIfNeeded()
        await page.waitForFunction(()=>[...document.querySelectorAll('#t2kav-gym img')].filter(i=>i.getBoundingClientRect().width>0).every(i=>i.complete))
        await page.screenshot({ path: 'anti-slop/verification/gym-mobile.png' })
      }
      if (width===1440) {
        await page.locator('#reusemart .project-gallery').scrollIntoViewIfNeeded()
        await page.locator('#reusemart .ag img').first().waitFor({state:'visible'})
        await page.waitForFunction(()=>document.querySelector('#reusemart .ag img').complete)
        assert.equal(fullRequests.filter(url=>url.includes('/reuse-')).length,0,'ReuseMart full captures downloaded before enlargement')
        await page.locator('#reusemart .project-gallery').screenshot({path:'anti-slop/verification/reusemart-desktop.png'})
        await page.getByRole('button',{name:'Enlarge ReuseMart: Storefront',exact:true}).click()
        await page.waitForFunction(()=>document.querySelector('dialog img')?.naturalWidth>0)
        assert.ok(fullRequests.some(url=>url.includes('/reuse-')))
        await page.screenshot({path:'anti-slop/verification/lightbox-desktop.png'})
        await page.keyboard.press('Escape')
        await page.locator('#reusemart .ag__selectors').getByRole('button',{name:'5. Buyer app',exact:true}).click()
        await page.waitForFunction(()=>document.querySelector('#reusemart .ag__panel[data-active="true"] img')?.naturalWidth>0)
        await page.locator('#reusemart .project-gallery').screenshot({path:'anti-slop/verification/reusemart-phone-desktop.png'})
        await page.locator('#t2kav-gym .project-gallery').scrollIntoViewIfNeeded()
        await page.waitForFunction(()=>document.querySelector('#t2kav-gym .ag__panel[data-active="true"] img')?.naturalWidth>0)
        await page.locator('#t2kav-gym .project-gallery').screenshot({path:'anti-slop/verification/gym-desktop.png'})
        const eagle = page.getByRole('group',{name:'EagleJeans screenshots',exact:true})
        await page.locator('#eaglejeans .project-gallery').scrollIntoViewIfNeeded()
        await eagle.getByRole('button',{name:'5. Staff sign-in',exact:true}).click()
        await page.waitForFunction(()=>document.querySelector('#eaglejeans .ag__panel[data-active="true"] img')?.naturalWidth>0)
        await page.locator('#eaglejeans .project-gallery').screenshot({path:'anti-slop/verification/eagle-iphone-gallery.png'})
        results.push({iphoneFrames:['Gym','ReuseMart','EagleJeans'], appHeaderBelowIsland:true})

        results.push({fullCaptureOnDemand:'pass'})
        await page.locator('#padukuhan-tritis .project-gallery').scrollIntoViewIfNeeded()
      }
      const melodia=page.locator('#spotify-clone .project-gallery')
      await melodia.scrollIntoViewIfNeeded()
      await melodia.locator('.ag').waitFor()
      assert.equal(await melodia.locator('.ag__selectors button').count(),5)
      for(let i=0;i<5;i++){
        await melodia.locator('.ag__selectors button').nth(i).click()
        await page.waitForFunction(()=>document.querySelector('#spotify-clone .ag__panel[data-active="true"] img')?.naturalWidth>0)
        const alt=await melodia.locator('.ag__panel[data-active="true"] img').getAttribute('alt')
        assert.ok(alt.startsWith('Melodia') && alt.length>40)
      }
      await melodia.getByRole('button',{name:'Enlarge Melodia (Spotify Clone): Mobile album',exact:true}).click()
      await page.getByRole('dialog').waitFor({state:'visible'})
      await page.waitForFunction(()=>document.querySelector('dialog img')?.naturalWidth>0)
      assert.equal(await page.getByRole('dialog').locator('img').evaluate(el=>getComputedStyle(el).objectFit),'contain')
      if(width===390)await page.screenshot({path:'anti-slop/verification/melodia-mobile-dialog.png'})
      await page.keyboard.press('Escape')
      if(width===1440){
        await melodia.locator('.ag__selectors button').first().click()
        await page.waitForFunction(()=>document.querySelector('#spotify-clone .ag__panel[data-active="true"] img')?.naturalWidth>0)
        await melodia.screenshot({path:'anti-slop/verification/melodia-desktop.png'})
      }
      if(width===390)await melodia.screenshot({path:'anti-slop/verification/melodia-mobile.png'})
      results.push({width,melodiaFiveImagesAndAlt:'pass',melodiaMobileImageFit:'contain'})
      await page.close()
    }
    const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
    let release
    const hold = new Promise(resolve=>{release=resolve})
    await page.route(/AccordionGallery(?:\.tsx|-[^/]+\.js)/, async route=>{await hold;await route.continue()})
    await page.goto('http://127.0.0.1:5183/')
    await page.locator('#eaglejeans .project-gallery').scrollIntoViewIfNeeded()
    const holder = page.locator('#eaglejeans .project-gallery')
    const before = await holder.boundingBox()
    release()
    await holder.locator('.ag').waitFor()
    const after = await holder.boundingBox()
    assert.ok(Math.abs(before.height-after.height)<1, `Skeleton shift ${before.height} => ${after.height}`)
    results.push({ skeletonBefore: before.height, skeletonAfter: after.height })
    const llms = await page.request.get('http://127.0.0.1:5183/llms.txt')
    assert.equal(llms.status(),200)
    assert.ok((await llms.text()).startsWith('# Gabriel'))
    const markdown = await page.request.get('http://127.0.0.1:5183/index.md')
    assert.equal(markdown.status(),200)
    assert.ok((await markdown.text()).includes('## ReuseMart'))
    const failurePage = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
    let broken = true
    await failurePage.route('**/EG2*.webp*', route => broken && route.request().resourceType()==='image' ? route.abort() : route.continue())
    await failurePage.goto('http://127.0.0.1:5183/#eaglejeans')
    await failurePage.locator('#eaglejeans .project-gallery').scrollIntoViewIfNeeded()
    await failurePage.getByText('Screenshot could not load.', {exact:true}).waitFor()
    broken = false
    await failurePage.getByRole('button', {name:'Try again',exact:true}).click()
    await failurePage.waitForFunction(()=>document.querySelector('#eaglejeans .ag img')?.naturalWidth>0)
    results.push({imageErrorAndRetry:'pass'})
    const deepLink = await browser.newPage({ viewport: {width:1440,height:900}, reducedMotion:'reduce' })
    await deepLink.goto('http://127.0.0.1:5183/#reusemart')
    await deepLink.waitForFunction(()=>{const r=document.getElementById('reusemart').getBoundingClientRect();return r.top>=0 && r.top<300})
    results.push({directProjectLink:'pass'})
    const animated = await browser.newPage({viewport:{width:1440,height:1000}})
    await animated.goto('http://127.0.0.1:5183/#reusemart')
    await animated.locator('#reusemart .project-gallery').scrollIntoViewIfNeeded()
    await animated.locator('#reusemart .ag__panel').last().hover()
    await animated.waitForFunction(()=>{
      const panels=[...document.querySelectorAll('#reusemart .ag__panel')]
      return panels[4].getBoundingClientRect().width > panels[0].getBoundingClientRect().width * 3.8
    })
    await animated.waitForFunction(()=>document.querySelector('#reusemart .ag__panel[data-active="true"] img')?.naturalWidth>0)
    await animated.locator('#reusemart .project-gallery').screenshot({path:'anti-slop/verification/hover-phone.png'})
    results.push({animatedHover:'pass'})
    assert.deepEqual(errors, [])
    await fs.writeFile('anti-slop/verification/results.json',JSON.stringify({results,errors},null,2))
    console.log(JSON.stringify({results,errors},null,2))
  } finally { await browser.close(); if (production) await new Promise(resolve=>server.httpServer.close(resolve)); else await server.close() }
})().catch(error=>{console.error(error);process.exitCode=1})
